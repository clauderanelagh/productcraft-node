// Emits the checked-in docs (api.md, the README generated region, examples/)
// and _generated/manifest.json (docs/sdk-standard.md section 8).

import { buildTrees, callExample, deprecationText, errorClass, pathValue } from "./emit-code.mjs";
import { anchorId, stableJson } from "./util.mjs";

export const README_START = "<!-- generated:start (scripts/gen-sdk.mjs; edits between the markers are overwritten) -->";
export const README_END = "<!-- generated:end -->";

const md = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ");

function signature(o, cfg) {
  const args = o.positional.map((p) => p.arg);
  if (o.paramsType) args.push(o.hasRequiredParams ? "params" : "params?");
  args.push("options?");
  const ret = o.paginated
    ? `PagePromise<${cfg.className}.${o.itemType}>`
    : o.success.kind === "void" ? "void" : o.success.kind === "raw" ? "Response" : `${cfg.className}.${o.responseType}`;
  const acc = o.scope?.accessor || o.scope?.name;
  const scope = o.scope ? (o.scope.token ? `.${acc}({ token })` : o.scope.args === "positional" ? `.${acc}(${o.scope.bind.map(() => "…").join(", ")})` : `.${acc}({ … })`) : "";
  return { call: `${cfg.clientVar}${scope}.${o.call}(${args.join(", ")})`, ret };
}

export function emitManifest(model, cfg) {
  const out = {};
  for (const o of model.ops) {
    const sig = signature(o, cfg);
    out[o.operationId] = {
      resource: o.resource, method: o.method, scope: o.scope?.name ?? null, http: `${o.http} ${o.path}`,
      signature: `${sig.call}: ${sig.ret}`, snippet: callExample(o, cfg, model.deref),
      params: o.paramsType ? `${cfg.className}.${o.paramsType}` : null, paginated: o.paginated, idempotent: o.idempotent,
      public: o.public, actor: o.actor, poll: o.poll, deprecated: o.deprecated,
    };
  }
  return stableJson({ package: cfg.packageName, operations: out });
}

export function emitApiMd(model, cfg) {
  const L = [`# ${cfg.packageName} API reference`, "", `<!-- Generated by scripts/gen-sdk.mjs from ${cfg.spec}. Do not edit. -->`];
  // scripts/check-snippets.mjs prepends this to every block below.
  L.push(`<!-- snippet-preamble: import { ${cfg.className} } from "${cfg.packageName}"; const ${cfg.clientVar} = new ${cfg.className}(); -->`, "");
  L.push(`Every method of \`${cfg.className}\`, grouped by resource. Types are under the \`${cfg.className}\` namespace (\`import type { ${cfg.className} } from "${cfg.packageName}"\`). Every method takes per-request options last (\`{ idempotencyKey, timeout, maxRetries, headers, signal, workspaceId }\`).`, "");
  const trees = buildTrees(model);
  const sections = [];
  const visit = (node, path, scope) => {
    if (node.ops.length || node.unwrap) sections.push({ node, path, scope });
    for (const k of [...node.children.keys()].sort()) visit(node.children.get(k), [...path, k], scope);
  };
  for (const [scope, tree] of trees) visit(tree, [], scope);
  for (const { node, path, scope } of sections) {
    const sc = model.scopes.find((s) => s.name === scope);
    const prefix = scope ? `${sc?.accessor || scope}(…)${path.length ? "." : ""}` : "";
    L.push(`## ${prefix}${path.join(".")}`, "");
    for (const o of [...node.ops].sort((a, b) => a.method.localeCompare(b.method))) {
      const sig = signature(o, cfg);
      L.push(`### \`${sig.call}\``, "");
      L.push(`\`${o.http} ${o.path}\` → \`${sig.ret}\`${o.deprecated ? " · **deprecated**" : ""}`, "");
      if (o.summary) L.push(o.summary + (o.summary.endsWith(".") ? "" : "."), "");
      if (o.deprecationNote) L.push(`**Deprecated:** ${deprecationText(o)}`, "");
      if (o.description) L.push(o.description, "");
      const facts = [];
      if (o.paramsType) facts.push(`Params: \`${cfg.className}.${o.paramsType}\``);
      if (o.paginated) facts.push("Paginated: `for await` iterates every item; `await` gives one page");
      if (o.idempotent) facts.push("Idempotent: an `Idempotency-Key` is sent automatically and reused on retries");
      if (o.public) facts.push("Public: no API key, browser-safe");
      if (o.credentials) facts.push(`Credential${o.credentials.optional ? " (optional)" : ""}: ${o.credentials.names.map((n) => `[\`${n}\`](#${n})`).join(" or ")}`);
      if (o.actor && o.scope?.actor) facts.push("Fills `actor_id` from `.as(actorId)`");
      if (o.poll) facts.push(`Polling: \`${o.resource}.poll(…)\` waits for \`${o.poll.field}\` ∈ ${o.poll.terminal.map((t) => `\`${t}\``).join(", ")}`);
      for (const f of facts) L.push(`- ${f}`);
      if (facts.length) L.push("");
      if (o.errors.length) {
        L.push("| Status | Error class | Codes | When |", "|---|---|---|---|");
        for (const e of o.errors) L.push(`| ${e.status} | \`${errorClass(e.status)}\` | ${e.codes.map((c) => `\`${c}\``).join(", ")} | ${md(e.description)} |`);
        L.push("");
      }
      L.push("```ts", callExample(o, cfg, model.deref), "```", "");
      L.push(`[HTTP reference](${cfg.docsUrl}/api-reference#${anchorId(o.http.toLowerCase(), o.path)})`, "");
    }
    if (node.unwrap) {
      L.push("### `" + cfg.clientVar + ".webhooks.unwrap({ payload, headers, secret? })`", "");
      L.push(`Verifies the signature and returns \`${cfg.className}.UnwrapWebhookEvent\`. Events: ${model.webhooks.map((h) => `\`${h.type}\``).join(", ")}, plus \`UnknownWebhookEvent\` for types added later.`, "");
      L.push("### `" + cfg.clientVar + ".webhooks.sign({ payload, secret?, id?, timestamp? })`", "");
      L.push("Signs a test event exactly as ProductCraft signs deliveries (Standard Webhooks) and returns `{ payload, headers }`, ready for `unwrap` or a request to your handler. For tests; real deliveries come signed.", "");
    }
  }
  if (model.securitySchemes) {
    L.push("## Credentials", "", `Routes take different credentials; each method above says which. Every one is sent as \`Authorization: Bearer\`. A workspace API key is the client's \`apiKey\` (or \`PRODUCTCRAFT_API_KEY\`); pass any other as \`new ${cfg.className}({ auth: { type: "bearer", token } })\`. The wrong one answers 401.`, "");
    for (const [name, scheme] of Object.entries(model.securitySchemes)) {
      // GitHub and npm anchor the heading as `#<name>`, which each method's Credential line links to.
      L.push(`### \`${name}\``, "", md(scheme.description ?? ""), "");
    }
  }
  if (model.errorCode) {
    L.push("## Error codes", "", "`err.code` on an `APIError` is one of these (an open set: new codes may appear).", "", "| Code | Meaning |", "|---|---|");
    for (const c of model.errorCode.values) L.push(`| \`${c}\` | ${md(model.errorCode.descriptions[c] ?? "")} |`);
    L.push("");
  }
  return L.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** A single-statement call example with request options added as the last argument. */
function withOptions(example, options) {
  const end = example.lastIndexOf(");");
  if (end === -1) throw new Error(`gen-sdk: cannot add options to ${example}`);
  return `${example.slice(0, end)}, ${options});${example.slice(end + 2)}`;
}

/** The README region between the generated markers. */
export function emitReadmeRegion(model, cfg) {
  const { className: C, clientVar: v, packageName: pkg } = cfg;
  // Representative ops for the README sections: the surface's `readme` choice when it names
  // one, else the first that fits, preferring ops a workspace key may call and that take no
  // positional argument (sdk review: a keyed client must not demo a session-only route).
  const pick = (named, fits) => {
    const byName = named && model.ops.find((o) => !o.scope && `${o.resource}.${o.method}` === named);
    if (named && !byName) throw new Error(`gen-sdk: readme op ${named} not found`);
    if (byName) return byName;
    const rank = (o) => (o.refusesWorkspaceKey ? 2 : 0) + (o.positional.length ? 1 : 0);
    return model.ops.filter((o) => !o.scope && fits(o)).sort((a, b) => rank(a) - rank(b))[0];
  };
  const firstList = pick(cfg.readme?.list, (o) => o.paginated && !o.hasRequiredParams);
  const firstRetrieve = model.ops.find((o) => o.method === "retrieve" && !o.scope && o.positional.length === 1 && o.success.kind === "json");
  const firstCreate = pick(cfg.readme?.create, (o) => o.method === "create" && o.idempotent);
  const pollOp = model.ops.find((o) => o.poll && !o.scope);
  // A client that can call `o`: the workspace key, or a person's session where the API refuses keys.
  const ctorFor = (o) => o?.refusesWorkspaceKey
    ? [`import { ${C} } from "${pkg}";`, "declare const sessionToken: string; // a signed-in person's access_token", `const ${v} = new ${C}({ auth: { type: "bearer", token: sessionToken } });`]
    : [`import { ${C} } from "${pkg}";`, `const ${v} = new ${C}({ apiKey: process.env.PRODUCTCRAFT_API_KEY });`];
  const ctor = ctorFor(null);
  const posArgs = (o) => o.positional.map((p, i) => JSON.stringify(pathValue(p, i, model.deref)));
  const argsWith = (o, ...rest) => [...posArgs(o), ...rest].join(", ");
  const L = [README_START, "", "## Resources", "", `Full reference: [api.md](./api.md).`, ""];
  const tops = new Map();
  for (const o of model.ops) {
    // Methods on a scope's root (empty resource) are listed under the scope itself.
    const key = (o.scope ? `${o.scope.accessor || o.scope.name}(…)` : "") + (o.segs.length ? `${o.scope ? "." : ""}${o.segs[0]}` : "");
    tops.set(key, [...(tops.get(key) ?? []), o]);
  }
  for (const k of [...tops.keys()].sort()) {
    const methods = tops.get(k).map((o) => (o.segs.length > 1 ? o.segs.slice(1).join(".") + "." : "") + o.method).sort();
    L.push(`- \`${v}.${k}\`: ${methods.map((m) => `\`${m}\``).join(", ")}`);
  }
  L.push("");
  if (firstList) {
    const m = `${firstList.resource}.${firstList.method}`;
    L.push("## Pagination", "", "List methods return a `PagePromise`: `for await` walks every item across pages, `await` gives one page.", "", "```ts", ...ctorFor(firstList),
      `for await (const item of ${v}.${m}(${argsWith(firstList, "{ limit: 50 }")})) console.log(item);`,
      `const page = await ${v}.${m}(${argsWith(firstList)});`, "if (page.hasNextPage()) await page.getNextPage();",
      `const all = await ${v}.${m}(${argsWith(firstList)}).toArray({ maxItems: 500 });`, "```", "");
  }
  L.push("## Errors", "", "Every failure is a class you can catch. `APIError` carries `status`, `code`, `message`, `errors[]`, `requestId` and `docUrl`.", "", "```ts",
    `import { ${C}, NotFoundError, RateLimitError, APIError } from "${pkg}";`, `const ${v} = new ${C}();`, "try {",
    firstRetrieve ? `  await ${v}.${firstRetrieve.resource}.retrieve("00000000-0000-0000-0000-000000000000");` : `  await Promise.resolve();`,
    "} catch (err) {", "  if (err instanceof NotFoundError) console.log(err.code, err.requestId, err.docUrl);",
    "  else if (err instanceof RateLimitError) console.log(err.retryAfter);", "  else if (err instanceof APIError) console.log(err.status, err.errors);", "  else throw err;", "}", "```", "");
  L.push("## Retries and timeouts", "", "Network errors, 408, 429, 5xx and `409 IDEMPOTENCY_IN_PROGRESS` are retried twice by default with exponential backoff and jitter, honouring `Retry-After` up to 60 s. A POST or PATCH without an idempotency key is never retried. Each attempt times out after 60 s, so the worst case with defaults is about 3 minutes; pass `signal: AbortSignal.timeout(ms)` for an overall deadline.", "", "```ts",
    ...(firstList?.refusesWorkspaceKey
      ? [ctorFor(firstList)[0], ctorFor(firstList)[1], `const ${v} = new ${C}({ auth: { type: "bearer", token: sessionToken }, maxRetries: 3, timeout: 20_000 });`]
      : [`import { ${C} } from "${pkg}";`, `const ${v} = new ${C}({ maxRetries: 3, timeout: 20_000 });`]),
    firstList ? `await ${v}.${firstList.resource}.${firstList.method}(${argsWith(firstList, "{}", "{ maxRetries: 0, signal: AbortSignal.timeout(5_000) }")});` : "", "```", "");
  if (firstCreate) {
    L.push("## Idempotency", "", "Writes that support it send an `Idempotency-Key` automatically and reuse it on every retry. Pass your own to make a retry across processes safe. If the API's idempotency store is unavailable it runs the request without it (fail-open), so a retry during that window can execute twice.", "", "```ts", ...ctorFor(firstCreate),
      withOptions(callExample(firstCreate, cfg, model.deref), `{ idempotencyKey: "order-1234" }`), "```", "");
  }
  if (pollOp) {
    L.push("## Polling", "", `\`${pollOp.resource}.poll(id)\` retrieves until \`${pollOp.poll.field}\` is terminal (${pollOp.poll.terminal.map((t) => `\`${t}\``).join(", ")}), honouring \`Retry-After\`; \`timeoutMs\` (default 5 min) throws \`APITimeoutError\`.`, "", "```ts", ...ctor,
      `const done = await ${v}.${pollOp.resource}.poll("${"9b2f6c1e-0d6a-4a63-9a43-2f1c3e4d5a6b"}", { intervalMs: 2_000, timeoutMs: 600_000 });`, `console.log(done.${pollOp.poll.field});`, "```", "");
    const create = model.ops.find((o) => o.resource === pollOp.resource && o.method === "create" && !o.scope && o.positional.length === 0);
    if (pollOp.poll.result && create) {
      const call = withOptions(callExample(create, cfg, model.deref), "{ timeoutMs: 600_000 }").replace(/^const \w+ = /, "const done = ").replace(`.create(`, ".createAndPoll<Extracted>(");
      L.push(`\`${pollOp.resource}.createAndPoll<T>(params)\` creates, then polls; \`${pollOp.poll.result}\` is typed as \`T\` (a type assertion: the SDK does not validate it at runtime).`, "", "```ts", ...ctor,
        "type Extracted = { title: string };", call, `console.log(done.${pollOp.poll.result}?.title);`, "```", "");
    }
  }
  if (model.webhooks.length) {
    const t = model.webhooks[0];
    L.push("## Webhooks", "", `\`${v}.webhooks.unwrap()\` verifies the signature against the **raw** body and returns a typed \`${C}.UnwrapWebhookEvent\`. The secret comes from \`{ secret }\`, the client's \`webhookSecret\`, or \`${cfg.webhookSecretEnv}\`.`, "",
      "Next.js route handler:", "", "```ts", `import { ${C} } from "${pkg}";`, `const ${v} = new ${C}();`, "export async function POST(req: Request) {",
      `  const event = await ${v}.webhooks.unwrap({ payload: await req.text(), headers: req.headers });`, "  switch (event.type) {", `    case ${JSON.stringify(t.type)}:`, "      console.log(event.data);", "      break;", "    default:", "      break; // UnknownWebhookEvent: types added later", "  }", "  return new Response(null, { status: 204 });", "}", "```", "",
      "Express (keep the body raw):", "", "```ts", 'import express from "express";', `import { ${C} } from "${pkg}";`, `const ${v} = new ${C}();`, "const app = express();",
      'app.post("/webhooks", express.raw({ type: "application/json" }), async (req, res) => {', `  const event = await ${v}.webhooks.unwrap({ payload: req.body, headers: req.headers });`, "  console.log(event.type);", "  res.sendStatus(204);", "});", "```", "",
      "Hono:", "", "```ts", 'import { Hono } from "hono";', `import { ${C} } from "${pkg}";`, `const ${v} = new ${C}();`, "const app = new Hono();",
      'app.post("/webhooks", async (c) => {', `  const event = await ${v}.webhooks.unwrap({ payload: await c.req.text(), headers: c.req.raw.headers });`, "  console.log(event.type);", "  return c.body(null, 204);", "});", "```", "");
    L.push("Testing a handler: `webhooks.sign()` signs an event the way ProductCraft does, so a test needs no live delivery and no hand-rolled HMAC.", "", "```ts", `import { ${C} } from "${pkg}";`, `const ${v} = new ${C}({ webhookSecret: "whsec_MfKQ9r8GKYqrTwjUPD8ILPZIo2LaLaSw" });`,
      `const { payload, headers } = await ${v}.webhooks.sign({ payload: { id: "evt_test_1", type: ${JSON.stringify(t.type)}, created_at: new Date().toISOString(), data: {} } });`,
      `const event = await ${v}.webhooks.unwrap({ payload, headers });`, "console.log(event.type);", "```", "");
  }
  if (firstRetrieve) {
    L.push("## Raw responses", "", "Every returned object has a non-enumerable `lastResponse` (`requestId`, `status`, `headers`). `.withResponse()` adds the `Response` and parsed rate-limit headers.", "", "```ts", ...ctor,
      `const id = "9b2f6c1e-0d6a-4a63-9a43-2f1c3e4d5a6b";`, `const obj = await ${v}.${firstRetrieve.resource}.retrieve(id);`, "console.log(obj.lastResponse.requestId);",
      `const { data, response, requestId, rateLimit } = await ${v}.${firstRetrieve.resource}.retrieve(id).withResponse();`, "console.log(data, response.status, requestId, rateLimit?.remaining);", "```", "");
  }
  L.push("## Testing", "", `\`${pkg}/testing\` exports \`createMockFetch()\`, a \`fetch\` that answers every operation with its spec example. Override one operation by name.${model.webhooks.length ? " It also exports \`signWebhook({ payload, secret })\`, which signs a test event for your webhook handler (the same as \`webhooks.sign()\`, without a client)." : ""}`, "", "```ts",
    `import { ${C} } from "${pkg}";`, `import { createMockFetch } from "${pkg}/testing";`, "const fetch = createMockFetch();",
    `const ${v} = new ${C}({ apiKey: "test", workspaceId: "9b2f6c1e-0d6a-4a63-9a43-2f1c3e4d5a6b", fetch });`,
    firstList ? `await ${v}.${firstList.resource}.${firstList.method}(${argsWith(firstList)});` : "", "console.log(fetch.calls.length);", "```", "");
  const raw = model.ops.find((o) => !o.scope && o.http === "GET" && o.positional.length === 0);
  if (raw) {
    L.push("## Escape hatch", "", "`.client` is the typed `openapi-fetch` client over the same credential and base URL (no retries). Use it for anything the resource methods do not cover.", "", "```ts", ...ctor,
      `const { data, error } = await ${v}.client.GET(${JSON.stringify(raw.path)}${raw.path.includes("{workspace_id}") ? `, { params: { path: { workspace_id: "9b2f6c1e-0d6a-4a63-9a43-2f1c3e4d5a6b" } } }` : ""});`, "console.log(data, error);", "```", "");
  }
  L.push(README_END);
  return L.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n").replace(/\n```\n\n```/g, "\n```\n\n```") + "\n";
}

export function spliceReadme(current, region) {
  const start = current.indexOf(README_START.slice(0, 22));
  const end = current.indexOf(README_END);
  if (start === -1 || end === -1) return current.trimEnd() + "\n\n" + region;
  return current.slice(0, start) + region + current.slice(end + README_END.length + 1);
}

/** `community(…).posts`, `admin.app(…)`, `apps`: what one examples file covers. */
const exampleLabel = (o) => (o.scope ? `${o.scope.accessor || o.scope.name}(…)${o.segs.length ? `.${o.segs[0]}` : ""}` : o.segs[0]);

/** examples/<surface>/<resource>.ts: one runnable file per top-level resource. */
export function emitExamples(model, cfg) {
  const files = {};
  const groups = new Map();
  for (const o of model.ops) {
    const key = (o.scope ? `${o.scope.name}${o.segs.length ? "-" : ""}` : "") + (o.segs[0] ?? "");
    groups.set(key, [...(groups.get(key) ?? []), o]);
  }
  for (const key of [...groups.keys()].sort()) {
    const ops = groups.get(key).sort((a, b) => a.name.localeCompare(b.name));
    const L = [
      `// Generated by scripts/gen-sdk.mjs from ${cfg.spec}. Do not edit.`,
      `// Every ${exampleLabel(ops[0])} call in ${cfg.packageName}. Run with PRODUCTCRAFT_API_KEY set.`,
      `import { ${cfg.className} } from "${cfg.packageName}";`,
      "",
      `const ${cfg.clientVar} = new ${cfg.className}();`,
      "",
    ];
    for (const o of ops) {
      L.push(`// ${o.name}: ${o.summary || o.http + " " + o.path}${o.deprecated ? " (deprecated)" : ""}`, "{", ...callExample(o, cfg, model.deref).split("\n").map((l) => "  " + l), "}", "");
    }
    L.push("export {};");
    files[`examples/${cfg.surface}/${key}.ts`] = L.join("\n") + "\n";
  }
  return files;
}
