export function emitClient(model, cfg) {
  const scopes = model.scopes.filter((s) => model.ops.some((o) => o.scope?.name === s.name));
  const imports = [`${cfg.className}Resources`, ...scopes.map((s) => `${cfg.className}${pascal(s.name)}`)].sort();
  const base = cfg.baseUrlKey ? `PC_BASE_URL.${cfg.baseUrlKey}` : lit(cfg.baseUrl);
  const L = [
    banner(cfg),
    `import { APIClient, createOpenAPIClient${cfg.baseUrlKey ? ", PC_BASE_URL" : ""}, type ClientOptions, type PollOptions as CorePollOptions, type RequestOptions as CoreRequestOptions } from "@productcraft/core";`,
    `import type { Client } from "openapi-fetch";`,
    `import type * as E from "./errors.js";`,
    `import type { paths } from "./paths.js";`,
    `import { ${imports.join(", ")} } from "./resources.js";`,
    `import * as T from "./types.js";`,
    model.webhooks.length ? `import ${model.apiEventTypes ? "type " : ""}* as W from "./webhooks.js";` : null,
    "",
    "declare const __PC_SDK_VERSION__: string | undefined;",
    `const VERSION = typeof __PC_SDK_VERSION__ === "string" ? __PC_SDK_VERSION__ : "0.0.0-dev";`,
    "",
    jsdoc([`${cfg.title}. Every method is generated from the API's OpenAPI document.`, "", "@example", "```ts", `import { ${cfg.className} } from ${lit(cfg.packageName)};`, `const ${cfg.clientVar} = new ${cfg.className}({ apiKey: process.env.PRODUCTCRAFT_API_KEY });`, "```"], ""),
    `export class ${cfg.className} extends ${cfg.className}Resources {`,
    "  #openapi?: Client<paths>;",
    "  constructor(options: ClientOptions = {}) {",
    `    super(new APIClient(options, ${base}, { name: ${lit(cfg.sdkName)}, version: VERSION }));`,
    "  }",
    "  /** The typed `openapi-fetch` escape hatch over the same credential and base URL. It does not retry. */",
    "  get client(): Client<paths> {",
    "    return (this.#openapi ??= createOpenAPIClient<paths>(this._client));",
    "  }",
  ];
  for (const s of scopes) {
    const cls = `${cfg.className}${pascal(s.name)}`;
    if (s.args === "positional") {
      const args = s.bind.map((b) => `${camel(b)}: string`).join(", ");
      L.push(jsdoc([s.doc ?? `Calls scoped to one ${s.bind.join(", ")}.`, ...s.bind.map((b) => `@param ${camel(b)} - \`{${b}}\``)], "  ").trimEnd());
      L.push(`  ${s.name}(${args}): ${cls} {`, `    return new ${cls}(this._client, { ${s.bind.map((b) => `${b}: ${camel(b)}`).join(", ")} });`, "  }");
    } else {
      const fields = Object.entries(s.args);
      L.push(jsdoc([s.doc ?? `Calls scoped to ${fields.map(([k]) => k).join(" + ")}.`], "  ").trimEnd());
      L.push(`  ${s.name}(scope: { ${fields.map(([k]) => `${k}: string`).join("; ")} }): ${cls} {`, `    return new ${cls}(this._client, { ${fields.map(([k, b]) => `${b}: scope.${k}`).join(", ")} });`, "  }");
    }
  }
  L.push("}", "");
  // Namespace members alias module-level `__<Name>` types, never `T.<Name>` directly:
  // the .d.ts bundler flattens `T.Job` to `Job`, and `export type Job = Job` inside
  // the namespace would refer to itself (TS2456; `any` under skipLibCheck).
  const ns = [];
  const aliases = [];
  const alias = (n, target) => {
    aliases.push(`type __${n} = ${target};`);
    ns.push(`  export type ${n} = __${n};`);
  };
  const typeOnly = (n, src) => alias(n, `${src}.${n}`);
  alias("RequestOptions", "CoreRequestOptions");
  alias("PollOptions", "CorePollOptions");
  for (const e of model.enums) {
    alias(e.name, `T.${e.name}`);
    ns.push(`  export const ${e.name} = T.${e.name};`);
  }
  const hookSchemas = new Set(model.webhooks.map((h) => h.schema));
  for (const m of model.models) if (!hookSchemas.has(m.schema)) typeOnly(m.name, "T");
  for (const o of model.ops) {
    if (o.paramsType) typeOnly(o.paramsType, "T");
    if (o.itemType && !model.models.some((m) => m.name === o.itemType)) typeOnly(o.itemType, "T");
    if (o.responseType && !model.models.some((m) => m.name === o.responseType)) typeOnly(o.responseType, "T");
  }
  alias("ErrorCode", `E.${cfg.className}ErrorCode`);
  for (const h of model.webhooks) typeOnly(h.typeName, "W");
  if (model.webhooks.length) {
    for (const n of ["UnknownWebhookEvent", "UnwrapWebhookEvent", "WebhookUnwrapParams"]) typeOnly(n, "W");
    if (!model.apiEventTypes) {
      alias("WebhookEventType", "W.WebhookEventType");
      ns.push("  export const WebhookEventType = W.WebhookEventType;");
    }
  }
  L.push(...aliases);
  L.push(`/** Public types: \`${cfg.className}.${model.models[0]?.name ?? "Model"}\`, \`${cfg.className}.${model.ops.find((o) => o.paramsType)?.paramsType ?? "Params"}\`, … */`);
  L.push(`export namespace ${cfg.className} {`, ...ns, "}");
  return L.filter((l) => l !== null).join("\n") + "\n";
}

