// Emits packages/<surface>/src/_generated/*.ts and the generated per-op test.

import openapiTS, { astToString } from "openapi-typescript";
import { applyResponseDefaults } from "./model.mjs";
import { anchorId, camel, jsdoc, pascal, placeholderUuid, sample, singular, stableJson, tsLiteral } from "./util.mjs";

const banner = (cfg) => `// Generated by scripts/gen-sdk.mjs from ${cfg.spec}. Do not edit.\n`;
const lit = JSON.stringify;
const opType = (o) => `paths[${lit(o.path)}][${lit(o.http.toLowerCase())}]`;

const ERROR_CLASS = { 400: "BadRequestError", 401: "AuthenticationError", 403: "PermissionDeniedError", 404: "NotFoundError", 409: "ConflictError", 422: "UnprocessableEntityError", 429: "RateLimitError" };
export const errorClass = (status) => ERROR_CLASS[status] ?? (status >= 500 ? "InternalServerError" : "APIError");

