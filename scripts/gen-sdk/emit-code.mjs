function bodyType(o) {
  return `NonNullable<${opType(o)}["requestBody"]>["content"][${lit(o.body.contentKey)}]`;
}
function okType(o) {
  return `${opType(o)}["responses"][${o.success.status}]["content"][${lit(o.success.contentKey)}]`;
}

export function emitTypes(model, cfg) {
  const hookSchemas = new Set(model.webhooks.map((h) => h.schema));
  const L = [banner(cfg), `import type { LastResponse } from "@productcraft/core";`, `import type { components, paths } from "./paths.js";`, ""];
  L.push(
    "type IsUnion<T, U = T> = T extends unknown ? ([U] extends [T] ? false : true) : never;",
    "type OpenString<T extends string> = string extends T ? T : true extends IsUnion<T> ? T | (string & {}) : T;",
    "type OpenValue<T> = [T] extends [string] ? OpenString<T> : T extends readonly (infer I)[] ? Open<I>[] : T extends object ? { [K in keyof T]: Open<T[K]> } : T;",
    "/** A response type: string-literal unions also accept values added after this SDK was built. */",
    "export type Open<T> = OpenValue<Exclude<T, null | undefined>> | Extract<T, null | undefined>;",
    "/** What a method resolves to: the parsed body plus non-enumerable `lastResponse`. */",
    "export type WithLastResponse<T> = T & { readonly lastResponse: LastResponse };",
    "/** Params inside a scope bound with `.as(actorId)`: `actor_id` may be left out. */",
    'export type WithOptionalActor<P> = P extends { actor_id: unknown } ? Omit<P, "actor_id"> & { actor_id?: P["actor_id"] } : P;',
    "/** A polled model whose free-form `K` the caller types as `R` (`createAndPoll<R>`); optional and nullable stay as declared. */",
    "export type WithResult<M, K extends keyof M, R> = Omit<M, K> & { [P in keyof M as P extends K ? P : never]: R | Extract<M[P], null> };",
    "",
  );
  for (const e of model.enums) {
    L.push(jsdoc([e.description], "").trimEnd() || "");
    L.push(`export type ${e.name} = components["schemas"][${lit(e.schema)}];`);
    L.push(`export const ${e.name} = { values: ${lit(e.values).replace(/,/g, ", ")} as const };`, "");
  }
  for (const m of model.models) {
    if (hookSchemas.has(m.schema)) continue;
    const doc = jsdoc([m.description], "");
    L.push(`${doc}export type ${m.name} = Open<components["schemas"][${lit(m.schema)}]>;`);
  }
  L.push("");
  for (const o of model.ops) {
    if (o.paramsType) {
      const parts = [];
      if (o.query.length) parts.push(`NonNullable<${opType(o)}["parameters"]["query"]>`);
      if (o.body?.json) parts.push(bodyType(o));
      else if (o.body) parts.push("{ body: BodyInit }");
      L.push(`/** Params for \`${o.name}\` (${o.http} ${o.path}). */`, `export type ${o.paramsType} = ${parts.join(" & ")};`);
    }
    if (o.itemType && !model.models.some((m) => m.name === o.itemType)) {
      L.push(`/** One item of \`${o.name}\`. */`, `export type ${o.itemType} = Open<${okType(o)}["data"][number]>;`);
    }
    if (o.responseType && !model.models.some((m) => m.name === o.responseType)) {
      L.push(`/** Response of \`${o.name}\`. */`, `export type ${o.responseType} = Open<${okType(o)}>;`);
    }
  }
  return L.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n") + "\n";
}

