// Example values (shared with the docs emitter and the per-op test)

/** Example value for a path parameter: its spec example, else a deterministic placeholder. */
export function pathValue(p, i, deref) {
  const s = deref(p.schema) ?? {};
  if (s.example !== undefined) return String(s.example);
  if (s.format === "uuid") return placeholderUuid(i + 1);
  return p.name.replace(/_(id|slug)$/, "") || "value";
}

/** Example params: required body fields and required query parameters (`full`: every query parameter). */
export function exampleParams(o, deref, { full = false } = {}) {
  if (!o.paramsType) return undefined;
  let out = {};
  if (o.body?.json) {
    const s = deref(o.body.schema) ?? {};
    out = sample(s, deref, "request") ?? {};
    if (o.body.isObject && Object.keys(out).length === 0 && !o.paginated) {
      const first = Object.entries(s.properties ?? {})[0];
      if (first) out = { [first[0]]: sample(first[1], deref, "response") };
    }
  }
  for (const q of o.query) {
    if (q.name === "cursor") continue;
    if (q.required || (full && q.name !== "actor_id")) out[q.name] = sample(q.schema, deref, "response");
  }
  if (o.scope?.actor && o.actor) delete out.actor_id;
  if (o.body && !o.body.json) out.body = "raw body";
  return out;
}

/** The scope prefix of a call: `.community("…").as("…")` or `.public({ … })`. */
export function scopeExpr(o, deref, given = undefined) {
  if (!o.scope) return "";
  const vals = given ?? Object.fromEntries(o.scope.bind.map((b, i) => [b, pathValue({ name: b, schema: o.pathParamSchemas?.[b] ?? { type: "string" } }, i + 4, deref)]));
  let expr;
  if (o.scope.args === "positional") expr = `.${o.scope.name}(${o.scope.bind.map((b) => lit(vals[b])).join(", ")})`;
  else expr = `.${o.scope.name}({ ${Object.entries(o.scope.args).map(([k, b]) => `${k}: ${lit(vals[b])}`).join(", ")} })`;
  if (o.scope.actor) expr += `.as(${lit(placeholderUuid(3))})`;
  return expr;
}

/** A short, runnable call example for one operation. */
export function callExample(o, cfg, deref) {
  const v = cfg.clientVar;
  const args = o.positional.map((p, i) => lit(pathValue(p, i, deref)));
  const params = exampleParams(o, deref);
  const optionalOnly = o.paramsType && !o.hasRequiredParams;
  if (params && !(optionalOnly && Object.keys(params).length === 0)) args.push(tsLiteral(params));
  const call = `${v}${scopeExpr(o, deref)}.${o.resource}.${o.method}(${args.join(", ")})`;
  const out = [];
  if (o.paginated) {
    const item = camel(singular(o.segs[o.segs.length - 1]));
    out.push(`for await (const ${item} of ${call}) {`, `  console.log(${item});`, "}");
    if (optionalOnly) out.push(`const page = await ${v}${scopeExpr(o, deref)}.${o.resource}.${o.method}(${[...o.positional.map((p, i) => lit(pathValue(p, i, deref))), "{}"].join(", ")}, { timeout: 5_000 });`);
  } else if (o.success.kind === "void") out.push(`await ${call};`);
  else if (o.success.kind === "raw") out.push(`const response = await ${call};`, "const text = await response.text();");
  else {
    const name = o.responseType && !/Response$/.test(o.responseType) ? camel(o.responseType) : "result";
    out.push(`const ${name} = await ${call};`);
  }
  return out.join("\n");
}

