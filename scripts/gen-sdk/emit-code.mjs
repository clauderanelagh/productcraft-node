export async function emitPaths(spec, cfg) {
  const ast = await openapiTS(applyResponseDefaults(spec), {
    emptyObjectsUnknown: true,
    exportType: true,
    defaultNonNullable: false,
    alphabetize: false,
  });
  return banner(cfg) + astToString(ast);
}

