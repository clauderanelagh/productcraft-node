const CORE_ERRORS = ["APIConnectionError", "APIError", "APITimeoutError", "APIUserAbortError", "AuthenticationError", "BadRequestError", "ConfigurationError", "ConflictError", "IdempotencyKeyReuseError", "InternalServerError", "NotFoundError", "PermissionDeniedError", "ProductCraftError", "RateLimitError", "UnprocessableEntityError", "WebhookVerificationError"];

export function emitErrors(model, cfg) {
  const L = [banner(cfg), `export { ${CORE_ERRORS.join(", ")} } from "@productcraft/core";`, ""];
  const name = `${cfg.className}ErrorCode`;
  const values = model.errorCode?.values ?? [];
  L.push(`/** Error codes this API documents. Open: codes added later still type-check. See https://productcraft.co/docs/errors. */`);
  L.push(`export type ${name} = ${[...values.map((v) => lit(v)), "(string & {})"].join(" | ")};`);
  L.push(`export const ${name} = { values: ${lit(values).replace(/,/g, ", ")} as const };`);
  return L.join("\n") + "\n";
}

export function emitWebhooks(model, cfg) {
  const L = [banner(cfg), `import type { WebhookHeaders, WebhookPayload } from "@productcraft/core";`];
  if (model.webhooks.length) L.push(`import type { components } from "./paths.js";`, `import type { Open } from "./types.js";`);
  L.push("", "/** Compile-time marker for event types this SDK does not know. Never a runtime value. */", "export declare const UnknownWebhookEventType: unique symbol;", "");
  for (const h of model.webhooks) {
    L.push(jsdoc([`\`${h.type}\`: ${h.summary}`, h.description && "", h.description], "").trimEnd());
    L.push(`export type ${h.typeName} = Open<components["schemas"][${lit(h.schema)}]> & { type: ${lit(h.type)} };`);
  }
  L.push(
    "/**",
    " * An event type this SDK version does not know yet (the API added it later): what `default:` receives.",
    " * `type` is declared as a unique symbol so `switch (event.type)` narrows each known case to its own",
    " * payload and leaves this type for `default:`. At runtime it is the event's type string (`String(event.type)`).",
    " */",
    "export interface UnknownWebhookEvent {",
    "  readonly type: typeof UnknownWebhookEventType;",
    "  readonly [key: string]: unknown;",
    "}",
    ...(model.apiEventTypes || !model.webhooks.length
      ? []
      : [
          `export type WebhookEventType = ${model.webhooks.map((h) => lit(h.type)).join(" | ")};`,
          `export const WebhookEventType = { values: ${lit(model.webhooks.map((h) => h.type)).replace(/,/g, ", ")} as const };`,
        ]),
    `/** Every event \`webhooks.unwrap\` can return: the known payloads, then \`UnknownWebhookEvent\`. */`,
    `export type UnwrapWebhookEvent = ${[...model.webhooks.map((h) => h.typeName), "UnknownWebhookEvent"].join(" | ")};`,
    "export interface WebhookUnwrapParams {",
    "  /** The raw request body (string or bytes). A parsed object throws: the signature covers the exact bytes. */",
    "  payload: WebhookPayload;",
    "  /** Node `IncomingHttpHeaders` or Fetch `Headers`. */",
    "  headers: WebhookHeaders;",
    `  /** Signing secret(s). Default: the client's \`webhookSecret\`, then \`${cfg.webhookSecretEnv}\`. */`,
    "  secret?: string | readonly string[];",
    "  /** Accepted clock skew in seconds. Default 300. */",
    "  toleranceSeconds?: number;",
    "}",
  );
  return L.join("\n") + "\n";
}

