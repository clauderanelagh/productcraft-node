/** Resource tree: one per scope ("" is the client root). */
export function buildTrees(model) {
  const trees = new Map([["", { children: new Map(), ops: [] }]]);
  for (const s of model.scopes) trees.set(s.name, { children: new Map(), ops: [] });
  for (const o of model.ops) {
    let node = trees.get(o.scope?.name ?? "");
    for (const seg of o.segs) {
      if (!node.children.has(seg)) node.children.set(seg, { children: new Map(), ops: [] });
      node = node.children.get(seg);
    }
    node.ops.push(o);
  }
  if (model.webhooks.length) {
    const root = trees.get("");
    if (!root.children.has("webhooks")) root.children.set("webhooks", { children: new Map(), ops: [] });
    root.children.get("webhooks").unwrap = true;
  }
  return trees;
}

function paramsSig(o) {
  if (!o.paramsType) return null;
  let t = `T.${o.paramsType}`;
  if (o.scope?.actor && (o.actor === "body" || o.actor === "both")) t = `T.WithOptionalActor<${t}>`;
  return `params${o.hasRequiredParams && !(o.scope?.actor && onlyActorRequired(o)) ? "" : "?"}: ${t}`;
}
const onlyActorRequired = (o) => o.requiredNames?.length === 1 && o.requiredNames[0] === "actor_id";

function returnType(o) {
  if (o.paginated) return `PagePromise<T.${o.itemType}>`;
  if (o.success.kind === "void") return "APIPromise<void>";
  if (o.success.kind === "raw") return "APIPromise<Response>";
  return `APIPromise<T.WithLastResponse<T.${o.responseType}>>`;
}

function specLiteral(o, argNames = {}) {
  const parts = [`method: ${lit(o.http)}`, `path: ${lit(o.path)}`];
  const pp = [];
  for (const b of o.bind) if (b !== "workspace_id") pp.push(`${b}: this._b.${b}`);
  for (const p of o.positional) {
    const value = argNames[p.name] ?? p.arg;
    pp.push(p.name === value ? p.name : `${p.name}: ${value}`);
  }
  if (pp.length) parts.push(`pathParams: { ${pp.join(", ")} }`);
  const actorQ = o.actor === "query" || o.actor === "both";
  const actorB = o.actor === "body" || o.actor === "both";
  if (o.paramsType) {
    const qNames = o.query.map((q) => q.name);
    if (o.body && !o.body.json) parts.push(`query: split(params, ["body"])[1]`, "body: params?.body");
    else if (o.body && qNames.length) {
      parts.push(`query: ${actorQ ? "fillActor(" : ""}split(params, ${lit(qNames)})[0]${actorQ ? ", this._b)" : ""}`);
      parts.push(`body: ${actorB ? "fillActor(" : ""}split(params, ${lit(qNames)})[1]${actorB ? ", this._b)" : ""}`);
    } else if (o.body) parts.push(`body: ${actorB ? "fillActor(params, this._b)" : "params"}`);
    else parts.push(`query: ${actorQ ? "fillActor(params, this._b)" : "params"}`);
  }
  if (o.idempotent) parts.push("idempotent: true");
  if (o.success.kind === "raw") parts.push("raw: true");
  if (o.public) parts.push("public: true");
  return `{ ${parts.join(", ")} }`;
}

function methodDoc(o, cfg, deref) {
  const lines = [o.summary || `${o.http} ${o.path}`];
  if (o.description) lines.push("", o.description);
  lines.push("");
  if (o.deprecated) lines.push(`@deprecated ${o.description || "Deprecated in the API."}`);
  for (const p of o.positional) lines.push(`@param ${p.arg} - ${p.description ?? `\`{${p.name}}\``}`);
  if (o.paramsType) lines.push(`@param params - \`${cfg.className}.${o.paramsType}\`${o.idempotent ? "" : ""}.`);
  lines.push(`@param options - Per-request options${o.idempotent ? " (an Idempotency-Key is sent automatically; override with `idempotencyKey`)" : ""}.`);
  for (const e of o.errors) lines.push(`@throws {${errorClass(e.status)}} ${e.status}${e.codes.length ? ` ${e.codes.join(", ")}` : ""}${e.description ? `: ${e.description}` : ""}`);
  lines.push(`@see ${o.http} ${o.path}`, `@see ${cfg.docsUrl}/api-reference#${anchorId(o.http.toLowerCase(), o.path)}`);
  lines.push("@example", "```ts", ...callExample(o, cfg, deref).split("\n"), "```");
  return jsdoc(lines, "  ");
}

function resourceClassName(prefix, path) {
  return `${prefix}${path.map(pascal).join("")}Resource`;
}

export function emitResources(model, cfg) {
  const trees = buildTrees(model);
  const classes = [];
  const { deref } = model;

  const emit = (node, path, prefix, scopeCfg) => {
    const isRoot = path.length === 0;
    const cls = isRoot ? (scopeCfg ? `${cfg.className}${pascal(scopeCfg.name)}` : `${cfg.className}Resources`) : resourceClassName(prefix, path);
    const kids = [...node.children.keys()].sort();
    for (const k of kids) emit(node.children.get(k), [...path, k], prefix, scopeCfg);
    const L = [];
    const label = isRoot ? (scopeCfg ? `\`${cfg.clientVar}.${scopeCfg.name}(…)\`` : `\`${cfg.clientVar}\``) : `\`${path.join(".")}\``;
    L.push(`/** ${label}${isRoot && scopeCfg?.doc ? `: ${scopeCfg.doc}` : ""} */`, `export class ${cls} extends APIResource {`);
    for (const k of kids) L.push(`  #${k}?: ${resourceClassName(prefix, [...path, k])};`);
    if (isRoot && scopeCfg?.actor) {
      L.push(
        jsdoc([`A copy of this scope that fills \`actor_id\` in every body or query that declares it, unless the call passes one.`, "@param actorId - The acting user."], "  ").trimEnd(),
        `  as(actorId: string): ${cls} {`,
        `    return new ${cls}(this._client, { ...this._b, actor_id: actorId });`,
        "  }",
      );
    }
    for (const k of kids) {
      const kc = resourceClassName(prefix, [...path, k]);
      L.push(`  get ${k}(): ${kc} {`, `    return (this.#${k} ??= new ${kc}(this._client, this._b));`, "  }");
    }
    for (const o of [...node.ops].sort((a, b) => a.method.localeCompare(b.method))) {
      const args = o.positional.map((p) => `${p.arg}: string`);
      const ps = paramsSig(o);
      if (ps) args.push(ps);
      args.push("options?: RequestOptions");
      L.push(methodDoc(o, cfg, deref).trimEnd());
      const call = o.paginated ? "list" : "request";
      L.push(`  ${o.method}(${args.join(", ")}): ${returnType(o)} {`, `    return this._client.${call}(${specLiteral(o)}, options);`, "  }");
      if (o.poll) emitPoll(L, o, node, cfg, deref);
    }
    if (node.unwrap) {
      L.push(
        jsdoc([
          "Verify a webhook's signature and parse it (Standard Webhooks, and the legacy `t=…,v1=…` scheme).",
          "",
          "@param params - The raw body, the request headers and optionally the secret.",
          "@throws {WebhookVerificationError} The signature, timestamp or payload is invalid.",
          "@throws {ConfigurationError} No secret was passed or configured.",
        ], "  ").trimEnd(),
        `  unwrap(params: WebhookUnwrapParams): Promise<UnwrapWebhookEvent> {`,
        `    return this._client.unwrapWebhook<UnwrapWebhookEvent>(params, ${lit(cfg.webhookSecretEnv)});`,
        "  }",
      );
    }
    L.push("}");
    classes.push(L.join("\n"));
  };
  for (const [scope, tree] of trees) {
    const scopeCfg = model.scopes.find((s) => s.name === scope);
    emit(tree, [], scopeCfg ? pascal(scopeCfg.name) : "", scopeCfg);
  }

  const head = [
    banner(cfg),
    `import type { APIClient, APIPromise, PagePromise, PollOptions, RequestOptions } from "@productcraft/core";`,
    `import type * as T from "./types.js";`,
    model.webhooks.length ? `import type { UnwrapWebhookEvent, WebhookUnwrapParams } from "./webhooks.js";` : null,
    "",
    "type Bound = Readonly<Record<string, string | undefined>>;",
    "",
    "/** Split params into [picked, rest] by key. */",
    "function split(params: object | undefined, keys: readonly string[]): [Record<string, unknown>, Record<string, unknown>] {",
    "  const picked: Record<string, unknown> = {};",
    "  const rest: Record<string, unknown> = {};",
    "  for (const [k, v] of Object.entries(params ?? {})) (keys.includes(k) ? picked : rest)[k] = v;",
    "  return [picked, rest];",
    "}",
    "",
    "/** Fill `actor_id` from a scope bound with `.as(actorId)`, unless the call passes one. */",
    "function fillActor<P>(params: P, bound: Bound): P {",
    "  if (bound.actor_id === undefined) return params;",
    "  const p = (params ?? {}) as Record<string, unknown>;",
    "  return (p.actor_id === undefined ? { ...p, actor_id: bound.actor_id } : p) as P;",
    "}",
    "",
    "export class APIResource {",
    "  protected readonly _client: APIClient;",
    "  /** Path parameters (and `actor_id`) bound by the enclosing scope. */",
    "  protected readonly _b: Bound;",
    "  constructor(client: APIClient, bound: Bound = {}) {",
    "    this._client = client;",
    "    this._b = bound;",
    "  }",
    "}",
    "",
    "void split;",
    "void fillActor;",
    "",
  ].filter((l) => l !== null);
  return head.join("\n") + classes.join("\n\n") + "\n";
}

function emitPoll(L, o, node, cfg, deref) {
  const config = `{ field: ${lit(o.poll.field)}, terminal: ${lit(o.poll.terminal).replace(/,/g, ", ")} }`;
  // With x-pc-sdk.poll.result the poll helpers are generic over that field.
  const res = o.poll.result;
  const model = `T.${o.responseType}`;
  const gen = res ? `<TResult = NonNullable<${model}[${lit(res)}]>>` : "";
  const shape = res ? `T.WithResult<${model}, ${lit(res)}, TResult>` : model;
  const rt = `Promise<T.WithLastResponse<${shape}>>`;
  const resultDoc = res ? ["", `@typeParam TResult - The shape you expect in \`${res}\`. It is a type assertion: the SDK does not validate it at runtime.`] : [];
  const args = [...o.positional.map((p) => `${p.arg}: string`), "options?: PollOptions"];
  L.push(
    jsdoc([`Retrieve until \`${o.poll.field}\` is ${o.poll.terminal.map((t) => `\`${t}\``).join(", ")}.`, ...resultDoc, "", "@param options - `intervalMs` (default 2 000), `timeoutMs` (default 300 000, then `APITimeoutError`), `signal`, and request options.", "@example", "```ts", `const done = await ${cfg.clientVar}.${o.resource}.poll(${o.positional.map(() => '"…"').join(", ")});`, "```"], "  ").trimEnd(),
    `  poll${gen}(${args.join(", ")}): ${rt} {`,
    `    return this._client.poll(${specLiteral(o)}, ${config}, options);`,
    "  }",
  );
  const create = node.ops.find((x) => x.method === "create" && x.success.kind === "json" && !x.paginated);
  // createAndPoll retrieves by the created object's `id`.
  if (!create || !deref(create.success.schema)?.properties?.id) return;
  const createNames = new Set(create.positional.map((p) => p.name));
  const unmatched = o.positional.filter((p) => !createNames.has(p.name));
  if (unmatched.length !== 1) return;
  const cargs = [...create.positional.map((p) => `${p.arg}: string`)];
  const ps = paramsSig(create);
  if (ps) cargs.push(ps);
  cargs.push("options?: PollOptions");
  const retrieve = specLiteral(o, { [unmatched[0].name]: "created.id" });
  L.push(
    jsdoc([`Create, then poll until \`${o.poll.field}\` is terminal. The Idempotency-Key goes on the create only.`, ...resultDoc, "", "@param options - Poll options (`intervalMs`, `timeoutMs`, `signal`) and request options for the create."], "  ").trimEnd(),
    `  createAndPoll${gen}(${cargs.join(", ")}): ${rt} {`,
    `    return this._client.createAndPoll<T.WithLastResponse<${shape}>>(`,
    `      ${specLiteral(create)},`,
    `      (created) => (${retrieve.replace("{ method", "{ method")}),`,
    `      ${config},`,
    "      options,",
    "    );",
    "  }",
  );
}

