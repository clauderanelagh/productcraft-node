// tests/_generated/operations.test.ts: one test per operation

export function emitOpsTest(model, cfg) {
  const { deref } = model;
  const WS = placeholderUuid(0);
  const L = [
    banner(cfg),
    `import { describe, expect, it } from "vitest";`,
    `import { ${cfg.className} } from "../../src/index.js";`,
    `import { createMockFetch } from "../../src/_generated/testing.js";`,
    "",
    `const WORKSPACE_ID = ${lit(WS)};`,
    "function setup(overrides: Parameters<typeof createMockFetch>[0] = {}) {",
    "  const fetch = createMockFetch(overrides);",
    `  const ${cfg.clientVar} = new ${cfg.className}({ apiKey: "pcft_test_key", workspaceId: WORKSPACE_ID, fetch, maxRetries: 0 });`,
    `  return { fetch, ${cfg.clientVar} };`,
    "}",
    "",
    `describe("generated operations (${cfg.surface})", () => {`,
  ];
  for (const o of model.ops) {
    const v = cfg.clientVar;
    // Distinct value per path parameter, so a swapped or misbound argument fails the path assertion.
    const values = { workspace_id: WS };
    for (const n of [...(o.scope?.bind ?? []), ...o.positional.map((p) => p.name)]) values[n] = `${n.replace(/_/g, "-")}-${Object.keys(values).length}`;
    const expectedPath = o.path.replace(/\{([^}]+)\}/g, (_, n) => encodeURIComponent(values[n]));
    const params = exampleParams(o, deref, { full: true });
    const args = o.positional.map((p) => lit(values[p.name]));
    if (params) args.push(tsLiteral(params, "    "));
    const call = `${v}${scopeExpr(o, deref, values)}.${o.resource}.${o.method}(${args.join(", ")})`;
    const query = [];
    const bodyExpect = {};
    for (const [k, val] of Object.entries(params ?? {})) {
      if (o.query.some((q) => q.name === k)) for (const item of Array.isArray(val) ? val : [val]) query.push([k, typeof item === "object" ? JSON.stringify(item) : String(item)]);
      else bodyExpect[k] = val;
    }
    const actor = o.scope?.actor ? placeholderUuid(3) : undefined;
    if (actor && (o.actor === "query" || o.actor === "both")) query.push(["actor_id", actor]);
    if (actor && (o.actor === "body" || o.actor === "both")) bodyExpect.actor_id = actor;
    query.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
    const overrides = o.poll ? `{ ${lit(o.name)}: { ...(${tsLiteral(sample(o.success.schema, deref, "response"))}), ${o.poll.field}: ${lit(o.poll.terminal[0])} } }` : "";
    L.push(`  it(${lit(`${o.name}: ${o.http} ${o.path}`)}, async () => {`, `    const { fetch, ${v} } = setup(${overrides});`);
    L.push(`    const result = await ${call};`);
    if (o.success.kind === "raw") L.push("    expect(result).toBeInstanceOf(Response);");
    else if (o.success.kind === "void") L.push("    expect(result).toBeUndefined();");
    else if (o.paginated) L.push("    expect(Array.isArray(result.data)).toBe(true);");
    else L.push("    expect(result).toBeDefined();");
    L.push(
      "    const call = fetch.calls[0]!;",
      `    expect(call.operation).toBe(${lit(o.name)});`,
      `    expect(call.method).toBe(${lit(o.http)});`,
      `    expect(call.url.pathname).toBe(${lit(expectedPath)});`,
      `    expect([...call.url.searchParams].sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]))).toEqual(${tsLiteral(query, "    ")});`,
      `    expect(call.headers.has("idempotency-key")).toBe(${o.idempotent});`,
      `    expect(call.headers.has("authorization")).toBe(${!o.public});`,
    );
    if (o.body?.json) L.push(`    expect(call.body).toEqual(${tsLiteral(bodyExpect, "    ")});`);
    if (o.poll) {
      const pa = o.positional.map((p) => lit(values[p.name])).join(", ");
      L.push(`    const polled = await ${v}.${o.resource}.poll(${pa}, { intervalMs: 1 });`, `    expect(polled.${o.poll.field}).toBe(${lit(o.poll.terminal[0])});`);
    }
    L.push("  });");
  }
  L.push("});");
  return L.join("\n") + "\n";
}

