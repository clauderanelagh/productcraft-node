// testing.ts: createMockFetch() from spec examples

export function emitTesting(model, cfg) {
  const { deref } = model;
  const routes = model.ops.map((o) => {
    const segs = o.path.split("/").map((s) => (/^\{.+\}$/.test(s) ? "[^/]+" : s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
    let body = null;
    if (o.success.kind === "json") {
      body = o.success.example ?? sample(o.success.schema, deref, "response");
      if (o.paginated && body && typeof body === "object") body = { ...body, pagination: { next_cursor: null, has_more: false } };
    } else if (o.success.kind === "raw") body = typeof o.success.example === "string" ? o.success.example : "";
    return {
      op: o.name, method: o.http, pattern: `^${segs.join("/")}$`, params: (o.path.match(/\{/g) ?? []).length,
      status: o.success.status, contentType: o.success.kind === "json" ? "application/json" : o.success.kind === "raw" ? o.success.contentType : null, body,
    };
  });
  // Static segments win over parameters: fewer parameters first, then longer paths.
  routes.sort((a, b) => a.params - b.params || b.pattern.length - a.pattern.length || a.op.localeCompare(b.op));
  const L = [
    banner(cfg),
    `/** Every operation name, as \`resource.method\`. */`,
    `export type OperationName = ${routes.map((r) => lit(r.op)).sort().join(" | ")};`,
    "",
    "interface Route { op: OperationName; method: string; pattern: RegExp; status: number; contentType: string | null; body: unknown }",
    "",
    "const ROUTES: Route[] = [",
    ...routes.map((r) => `  { op: ${lit(r.op)}, method: ${lit(r.method)}, pattern: /${r.pattern.replace(/\//g, "\\/")}/, status: ${r.status}, contentType: ${lit(r.contentType)}, body: ${tsLiteral(r.body, "  ")} },`),
    "];",
    "",
    "/** One request the mock received. */",
    "export interface MockCall {",
    "  /** The matched operation, or `undefined` when nothing matched (the mock answers 404). */",
    "  operation: OperationName | undefined;",
    "  method: string;",
    "  url: URL;",
    "  headers: Headers;",
    "  /** The JSON-parsed body (the raw value when it is not JSON). */",
    "  body: unknown;",
    "}",
    "/** Answers one call: a `Response`, or a value sent as JSON with the operation's success status. */",
    "export type MockHandler = (call: MockCall) => unknown;",
    "export interface MockFetch {",
    "  (input: string | URL | Request, init?: RequestInit): Promise<Response>;",
    "  /** Every call, in order. */",
    "  readonly calls: MockCall[];",
    "}",
    "",
    "/**",
    ` * A \`fetch\` that answers every ${cfg.className} operation with its spec example, for unit tests.`,
    " * Override an operation with a value (sent as its JSON body) or a handler.",
    " *",
    " * @example",
    " * ```ts",
    ` * const fetch = createMockFetch();`,
    ` * const ${cfg.clientVar} = new ${cfg.className}({ apiKey: "test", workspaceId: "9b2f6c1e-0d6a-4a63-9a43-2f1c3e4d5a6b", fetch });`,
    " * ```",
    " */",
    "export function createMockFetch(overrides: Partial<Record<OperationName, unknown>> = {}): MockFetch {",
    "  const calls: MockCall[] = [];",
    "  const mock = async (input: string | URL | Request, init?: RequestInit): Promise<Response> => {",
    "    const request = input instanceof Request ? input : undefined;",
    "    const url = new URL(request ? request.url : String(input));",
    "    const method = (init?.method ?? request?.method ?? \"GET\").toUpperCase();",
    "    const headers = new Headers(init?.headers ?? request?.headers);",
    "    const raw = init?.body ?? (request ? await request.text() : undefined);",
    "    let body: unknown = raw;",
    "    if (typeof raw === \"string\") {",
    "      try {",
    "        body = JSON.parse(raw);",
    "      } catch {",
    "        body = raw;",
    "      }",
    "    }",
    "    const route = ROUTES.find((r) => r.method === method && r.pattern.test(url.pathname));",
    "    const call: MockCall = { operation: route?.op, method, url, headers, body };",
    "    calls.push(call);",
    "    const requestId = `req_mock_${calls.length}`;",
    "    if (!route) {",
    "      return Response.json({ statusCode: 404, code: \"NOT_FOUND\", message: `No mock for ${method} ${url.pathname}` }, { status: 404, headers: { \"x-request-id\": requestId } });",
    "    }",
    "    let value: unknown = route.body;",
    "    if (route.op in overrides) {",
    "      const o = overrides[route.op];",
    "      value = typeof o === \"function\" ? await (o as MockHandler)(call) : o;",
    "      if (value instanceof Response) return value;",
    "    }",
    "    if (route.contentType === null || route.status === 204) return new Response(null, { status: route.status, headers: { \"x-request-id\": requestId } });",
    "    const text = route.contentType === \"application/json\" ? JSON.stringify(value) : String(value);",
    "    return new Response(text, { status: route.status, headers: { \"content-type\": route.contentType, \"x-request-id\": requestId } });",
    "  };",
    "  return Object.assign(mock, { calls });",
    "}",
  ];
  return L.join("\n") + "\n";
}

